/**
 * Скрытая ротация раскладов: сложность чередуется внутри бесконечной
 * лестницы уровней. Игроку ничего об этом не сообщается — просто
 * разные доски от уровня к уровню.
 */

/** Индекс расклада (1..5) для бесконечного уровня */
export function difficultyForLevel(level: number): number {
  return ((level - 1) % 5) + 1;
}
